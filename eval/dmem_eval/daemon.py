"""Lifecycle management for a dedicated dMem daemon instance.

The evaluation owns its daemon so that runs are reproducible and never touch an
existing user memory store. The daemon config is generated from the evaluation
config, including the embedding provider that powers semantic recall.
"""

from __future__ import annotations

import json
import os
import signal
import sqlite3
import subprocess
import time
from pathlib import Path
from typing import Any, Callable

import requests

_PENDING_JOB_SQL = """
SELECT count(*) FROM jobs
WHERE job_type IN ('embed_memory', 'rebuild_semantic')
  AND status IN ('pending', 'waiting', 'running', 'retrying')
"""

_UNEMBEDDED_SQL = """
SELECT count(*) FROM memory_projections
WHERE searchable = 1 AND embedding_state <> 'current'
"""


def _toml_string(value: str) -> str:
    return json.dumps(str(value), ensure_ascii=False)


def effective_dmem(config: Any, overlay: dict[str, Any] | None = None) -> dict[str, Any]:
    """Merge an ablation overlay into the configured ``dmem`` section.

    Supported overlay keys are ``graph_policy`` (a dMem graph policy string) and
    ``embedding`` (a boolean toggling the embedding provider). Everything else is
    inherited from the evaluation config so every mode shares one built index.
    """

    dmem = dict(config.section("dmem"))
    overlay = overlay or {}
    if overlay.get("graph_policy") is not None:
        dmem["graph_policy"] = str(overlay["graph_policy"])
    if overlay.get("embedding") is not None:
        embedding = dict(dmem.get("embedding") or {})
        embedding["enabled"] = bool(overlay["embedding"])
        dmem["embedding"] = embedding
    return dmem


def render_daemon_config(
    config: Any, data_dir: Path, overlay: dict[str, Any] | None = None
) -> str:
    """Render a dMem TOML config for the evaluation instance."""

    dmem = effective_dmem(config, overlay)
    embedding = dmem.get("embedding") or {}
    lines: list[str] = [
        "# Generated by eval/run_eval.py. Do not edit by hand.",
        "config_version = 1",
        "",
        "[instance]",
        f"data_dir = {_toml_string(str(data_dir))}",
        'database_filename = "dmem.db"',
        "",
        "[server]",
        f"listen_address = {_toml_string(str(dmem.get('listen_address') or '127.0.0.1:17373'))}",
        'shutdown_grace_period = "15s"',
        "",
        "[jobs]",
        f"worker_count = {int(dmem.get('worker_count') or 8)}",
        "queue_soft_limit = 10000",
        "queue_hard_limit = 20000",
        "max_attempts = 5",
        'lease_duration = "30s"',
        'per_job_timeout = "2m"',
        'retry_initial_backoff = "1s"',
        'retry_max_backoff = "5m"',
        "",
        "[storage]",
        "disk_soft_free_bytes = 1073741824",
        "disk_hard_free_bytes = 268435456",
        "",
        "[graph]",
        f"policy = {_toml_string(str(dmem.get('graph_policy') or 'features_only'))}",
        "",
        "# The Agent Tool route does not use a daemon-side processing provider.",
        "[processing]",
        "enabled = false",
        "",
        "[embedding]",
        f"enabled = {'true' if embedding.get('enabled') else 'false'}",
    ]
    if embedding.get("enabled"):
        lines += [
            "",
            "[embedding.provider]",
            'kind = "openai-compatible"',
            f"endpoint = {_toml_string(str(embedding.get('endpoint')))}",
            f"model = {_toml_string(str(embedding.get('model')))}",
            "telemetry_disabled = true",
            "",
            "[embedding.provider.secret]",
            'source = "environment"',
            f"name = {_toml_string(str(embedding.get('api_key_env') or 'DMEM_PROVIDER_KEY'))}",
            "",
            "[embedding.provider.options]",
            f"dimensions = {int(embedding.get('dimensions') or 0)}",
            f"query_instructions = {_toml_string(str(embedding.get('query_instructions') or ''))}",
            "",
            "[embedding.provider.limits]",
            f"max_egress_input_chars = {int(embedding.get('max_egress_input_chars') or 30000)}",
            f"max_response_bytes = {int(embedding.get('max_response_bytes') or 1048576)}",
            f"request_timeout = {_toml_string(str(embedding.get('request_timeout') or '60s'))}",
            f"max_concurrent = {int(embedding.get('max_concurrent') or 16)}",
            f"requests_per_minute = {int(embedding.get('requests_per_minute') or 300)}",
            "",
            "[embedding.provider.policy]",
            'default = "deny"',
            'query = "allow"',
            'content_types = ["text/plain"]',
            # Agent Tool commits store their raw event as source_type tool_call.
            'source_types = ["tool_call", "manual", "message", "conversation"]',
            'sensitivities = ["normal", "sensitive"]',
            "",
            "[[embedding.provider.policy.assignments]]",
            'selector = "space_type"',
            'space_type = "project"',
            'effect = "allow"',
            "priority = 100",
            "",
            "[[embedding.provider.policy.assignments]]",
            'selector = "space_type"',
            # Recall resolves the ancestor chain, so the root user scope must be
            # allowed too or every semantic query is policy-denied.
            'space_type = "user"',
            'effect = "allow"',
            "priority = 90",
        ]
    lines.append("")
    return "\n".join(lines)


class ManagedDaemon:
    """Runs ``dmemd init`` and ``dmemd daemon`` for one evaluation run."""

    def __init__(
        self,
        config: Any,
        run_dir: Path,
        *,
        overlay: dict[str, Any] | None = None,
        name: str = "daemon",
        data_dir: str | None = None,
        log: Callable[[str], None] = print,
    ) -> None:
        self.config = config
        self.run_dir = run_dir
        self.log = log
        self.dmem = effective_dmem(config, overlay)
        self.overlay = dict(overlay or {})
        self.name = name
        self.daemon_dir = run_dir / name
        configured_data_dir = str(data_dir or self.dmem.get("data_dir") or "").strip()
        if configured_data_dir:
            self.data_dir = config.resolve_path(configured_data_dir)
        else:
            # Every daemon variant of one run shares the index built by the
            # ``build`` phase, so the default data dir never depends on ``name``.
            self.data_dir = run_dir / "daemon" / "data"
        self.config_path = self.daemon_dir / "config.toml"
        self.log_path = self.daemon_dir / "daemon.log"
        self.database_path = self.data_dir / "dmem.db"
        # The daemon is started on listen_address, so that is the authoritative endpoint.
        self.endpoint = (
            f"http://{self.dmem.get('listen_address') or '127.0.0.1:17373'}"
        ).rstrip("/")
        # Relative paths are documented as config-relative.
        self.binary = config.resolve_path(str(self.dmem.get("binary")))
        self._process: subprocess.Popen | None = None
        self._log_handle = None

    # -- lifecycle ---------------------------------------------------------
    def start(self) -> None:
        self.daemon_dir.mkdir(parents=True, exist_ok=True)
        self.config_path.write_text(
            render_daemon_config(self.config, self.data_dir, self.overlay),
            encoding="utf-8",
        )
        if not self.database_path.exists():
            self._run(["init"], "init")
        self._spawn()
        self._wait_for_ready()

    def stop(self) -> None:
        if self._process is None:
            return
        process = self._process
        self._process = None
        if process.poll() is None:
            process.send_signal(signal.SIGTERM)
            try:
                process.wait(timeout=20)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait(timeout=10)
        if self._log_handle is not None:
            self._log_handle.close()
            self._log_handle = None

    def _run(self, args: list[str], label: str) -> None:
        command = [str(self.binary), "--config", str(self.config_path), *args]
        result = subprocess.run(command, capture_output=True, text=True)
        if result.returncode != 0:
            raise RuntimeError(
                f"dmemd {label} failed ({result.returncode}): "
                f"{result.stderr.strip() or result.stdout.strip()}"
            )

    def _spawn(self) -> None:
        self._log_handle = self.log_path.open("a", encoding="utf-8")
        command = [str(self.binary), "--config", str(self.config_path), "daemon"]
        self._process = subprocess.Popen(
            command,
            stdout=self._log_handle,
            stderr=subprocess.STDOUT,
            start_new_session=True,
        )

    def _wait_for_ready(self) -> None:
        deadline = time.time() + float(self.dmem.get("startup_timeout_seconds") or 90)
        url = f"{self.endpoint}/v1/capabilities"
        while time.time() < deadline:
            if self._process is not None and self._process.poll() is not None:
                raise RuntimeError(
                    f"dmemd exited early with code {self._process.returncode}; see {self.log_path}"
                )
            try:
                response = requests.get(url, timeout=3)
                if response.status_code == 200:
                    self.log(f"  dMem daemon ready at {self.endpoint}")
                    return
            except requests.RequestException:
                pass
            time.sleep(0.5)
        raise RuntimeError(f"dmemd did not become ready within the startup timeout; see {self.log_path}")

    # -- readiness helpers -------------------------------------------------
    def wait_for_indexing(self) -> dict[str, int]:
        """Wait until no embedding/rebuild jobs remain and projections are current."""

        embedding = (self.dmem.get("embedding") or {})
        if not embedding.get("enabled"):
            return {"pending_jobs": 0, "unembedded_projections": 0, "waited_seconds": 0}
        timeout = float(self.dmem.get("indexing_timeout_seconds") or 1800)
        deadline = time.time() + timeout
        last = {"pending_jobs": -1, "unembedded_projections": -1}
        started = time.time()
        while time.time() < deadline:
            counts = self._index_counts()
            if counts is not None:
                last = counts
                if counts["pending_jobs"] == 0 and counts["unembedded_projections"] == 0:
                    waited = round(time.time() - started, 1)
                    self.log(f"  semantic index ready after {waited}s")
                    return {**counts, "waited_seconds": waited}
            time.sleep(float(self.dmem.get("settle_seconds") or 2.0))
        raise RuntimeError(
            f"semantic index did not settle within {timeout}s; last counts: {last}"
        )

    def _index_counts(self) -> dict[str, int] | None:
        if not self.database_path.exists():
            return None
        try:
            connection = sqlite3.connect(
                f"file:{self.database_path}?mode=ro", uri=True, timeout=5
            )
        except sqlite3.Error:
            return None
        try:
            pending = connection.execute(_PENDING_JOB_SQL).fetchone()[0]
            unembedded = connection.execute(_UNEMBEDDED_SQL).fetchone()[0]
            return {"pending_jobs": int(pending), "unembedded_projections": int(unembedded)}
        except sqlite3.Error:
            return None
        finally:
            connection.close()

    def __enter__(self) -> "ManagedDaemon":
        self.start()
        return self

    def __exit__(self, *exc_info: Any) -> None:
        self.stop()
